const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
const path = require('node:path');
const context = vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(__dirname, '../scripts/xirr-math.js'), 'utf8'), context);
const { calculate, parseText, dateDay } = context.XirrMath;
const near = (actual, expected, tolerance = 1e-8) => assert.ok(Math.abs(actual - expected) < tolerance, `${actual} != ${expected}`);
const flow = (date, amount) => ({ date, amount });
const official = [flow('2008-01-01', -10000), flow('2008-03-01', 2750), flow('2008-10-30', 4250), flow('2009-02-15', 3250), flow('2009-04-01', 2750)];
const result = calculate({ flows: official, targetRate: .09 });
assert.equal(result.status, 'unique');
near(result.rate, .373362535);
near(result.targetNpv, 2086.647602031535, 1e-7);
near(result.residual, 0, 1e-7);
assert.equal(result.invested, 10000);
assert.equal(result.recovered, 13000);
assert.equal(result.profit, 3000);
near(result.simpleReturn, .3);
near(calculate({ flows: official.slice().reverse() }).rate, result.rate);
const simple = [flow('2025-01-01', -1000000), flow('2026-01-01', 1100000)];
near(calculate({ flows: simple }).rate, .1);
near(calculate({ flows: [simple[0]], terminal: { date: simple[1].date, amount: 1100000 } }).rate, .1);
near(calculate({ flows: [flow('2025-01-01', -1000000), flow('2026-01-01', 400000)], terminal: { date: '2026-01-01', amount: 700000 } }).rate, .1);
near(calculate({ flows: [flow('2025-01-01', -100), flow('2026-01-01', 50)] }).rate, -.5);
near(calculate({ flows: [flow('2025-01-01', -100), flow('2026-01-01', 100)] }).rate, 0);
near(calculate({ flows: [flow('2025-01-01', -100), flow('2026-01-01', 1000000)] }).rate, 9999, 1e-6);
near(calculate({ flows: [flow('2025-01-01', -100), flow('2026-01-01', .01)] }).rate, -.9999);
const grouped = calculate({ flows: [flow('2025-01-01', -150), flow('2025-01-01', 50), flow('2026-01-01', 110)] });
near(grouped.rate, .1);
assert.equal(grouped.invested, 150);
assert.equal(grouped.recovered, 160);
assert.equal(grouped.signChanges, 1);
near(calculate({ flows: [flow('2024-01-01', -100), flow('2025-01-01', 110)] }).rate, 1.1 ** (365 / 366) - 1);
near(calculate({ flows: [flow('2025-01-01', -100), flow('2025-01-02', 101)] }).rate, 1.01 ** 365 - 1, 1e-7);
const multiple = calculate({ flows: [flow('2021-01-01', -100), flow('2022-01-01', 230), flow('2023-01-01', -132)] });
assert.equal(multiple.status, 'non-conventional');
assert.equal(multiple.rate, null);
assert.equal(multiple.candidates.length, 2);
near(multiple.candidates[0], .1);
near(multiple.candidates[1], .2);
const tangent = calculate({ flows: [flow('2021-01-01', -100), flow('2022-01-01', 200), flow('2023-01-01', -100)] });
assert.equal(tangent.status, 'non-conventional');
assert.equal(tangent.rate, null);
assert.equal(tangent.candidates.length, 1);
near(tangent.candidates[0], 0);
assert.equal(calculate({ flows: [flow('2021-01-01', -100), flow('2022-01-01', 100), flow('2023-01-01', -100)] }).candidates.length, 0);
assert.equal(calculate({ flows: [flow('2025-01-01', -100)], terminal: { date: '2026-01-01', amount: 0 } }).status, 'no-root');
assert.equal(calculate({ flows: [flow('2025-01-01', -100), flow('2025-01-01', 110)] }).status, 'same-day');
assert.equal(calculate({ flows: [flow('2025-01-01', -100), flow('2025-01-01', 100)] }).status, 'indeterminate');
assert.equal(calculate({ flows: [flow('2025-01-01', -100), flow('2025-01-02', 1000)] }).status, 'outside-range');
assert.throws(() => calculate({ flows: [] }), /현금흐름/);
assert.throws(() => calculate({ flows: [flow('2025-01-01', 100)] }), /투자금/);
assert.throws(() => calculate({ flows: [flow('2025-02-29', -100)] }), /달력/);
assert.throws(() => calculate({ flows: [flow('', -100)] }), /날짜/);
assert.throws(() => calculate({ flows: [flow('2025-01-01', NaN)] }), /금액/);
assert.throws(() => calculate({ flows: [flow('2025-01-01', '100')] }), /금액/);
assert.throws(() => calculate({ flows: [flow('2025-01-01', -.001)] }), /소수/);
assert.throws(() => calculate({ flows: simple, terminal: { date: '2025-12-31', amount: 0 } }), /평가일/);
assert.throws(() => calculate({ flows: simple, terminal: { date: '2026-01-01', amount: -1 } }), /평가금액/);
assert.throws(() => calculate({ flows: simple, targetRate: -1 }), /목표/);
assert.throws(() => calculate({ flows: simple, targetRate: NaN }), /목표/);
assert.throws(() => calculate({ flows: [flow('1900-01-01', -100), flow('2100-01-01', 200)] }), /100년/);
assert.throws(() => calculate({ flows: Array.from({ length: 201 }, () => simple[0]) }), /200/);
assert.throws(() => calculate({ flows: [flow('2025-01-01', -1e12 - 1)] }), /1조/);
assert.throws(() => calculate({ flows: Array.from({ length: 11 }, () => flow('2025-01-01', -1e12)) }), /10조/);
assert.equal(dateDay('2024-03-01') - dateDay('2024-02-28'), 2);
assert.throws(() => dateDay('2100-02-29'), /달력/);
const pasted = parseText('\uFEFF날짜\t금액\r\n2025/1/1\t-1,000.25\r\n2026.1.1\t1,100.25');
assert.equal(pasted.length, 2);
assert.equal(pasted[0].date, '2025-01-01');
assert.equal(pasted[0].amount, -1000.25);
assert.equal(parseText('date,amount\n2025-01-01,"-1,000"\n2026-01-01,1100')[0].amount, -1000);
for (const text of ['', '2025-01-01,-1,000', '2025-02-29,-1', '2025-01-01,NaN', '2025-01-01,1.234', '<script>,100', '2025-01-01,1,2', 'date,amount']) assert.throws(() => parseText(text));
console.log('XIRR_MATH_VALID');
